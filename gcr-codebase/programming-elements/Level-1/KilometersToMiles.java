// Writing a program to convert the distance from kilometers to miles

// Create KilometersToMiles class to convert the distance from kilometers to miles
public class KilometersToMiles
{
  public static void main(String []args)
  {
    // Create a variable to indicate the distance in kilometer
     double disInKilo=10.8;
      
    // Create a variable to convert the distance in Miles
    double disInMiles= disInKilo*(1.6);
    
    // Print the distance in Miles
     System.out.println("The distance 10.8km in miles is :"+ disInMiles);
  }

}